"""Compute magnitude-constrained nonlinear stress tests from saved component scores (SI H.5)."""
from pathlib import Path
import argparse
import csv
import hashlib
import io
import json
import platform
import sys
import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
PANEL_NAMES = {'PHH': 'PHH', 'external': 'DILImap', 'source': 'Within-source holdout'}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def H(x):
    return (x > 0).astype(float) + 0.5 * (x == 0)


def rho(D, E):
    r = np.zeros_like(D, dtype=float)
    nz = D != 0
    r[nz & (np.abs(E) > np.abs(D))] = 1.0
    r[nz & (np.abs(E) == np.abs(D))] = 0.5
    r[(~nz) & (E != 0)] = 0.5
    return r


def load_compounds(path, arm):
    with np.load(path, allow_pickle=False) as z:
        col = list(z['arm_names']).index(arm)
        compounds = np.unique(z['compound'])
        masks = [z['compound'] == c for c in compounds]
        assert all(len(np.unique(z['label'][m])) == 1 for m in masks)
        y = np.array([int(z['label'][m][0]) for m in masks])
        assert set(y) == {0, 1}
        scores = {key: np.array([z[key][m, col].mean() for m in masks])
                  for key in ['linear', 'kernel', 'full']}
        assert all(np.all(np.isfinite(x)) for x in scores.values())
        intercept = scores['full'] - scores['linear'] - scores['kernel']
        assert np.ptp(intercept) < 1e-10, 'Saved decomposition has no common intercept'
        rows = [{'compound': str(c), 'label': int(y[k]),
                 'profiles': int(masks[k].sum()),
                 **{key: float(val[k]) for key, val in scores.items()}}
                for k, c in enumerate(compounds)]
    return scores['linear'], scores['kernel'], y, rows


def evaluate(ell, g, y, t, grid_points, signs, tol):
    pos, neg = np.flatnonzero(y == 1), np.flatnonzero(y == 0)
    i, j = np.repeat(pos, len(neg)), np.tile(neg, len(pos))
    D, E = ell[i] - ell[j], t * (g[i] - g[j])
    baseline = H(D)
    B = float(rho(D, E).mean())

    def movement(h):
        e = h[i] - h[j]
        assert np.all(np.abs(e) <= np.abs(E) + tol)
        delta = H(D + e) - baseline
        A = float(np.abs(delta).mean())
        assert A <= B + tol
        return {'A': A, 'Delta': float(delta.mean()),
                'changed_pairs': int(np.count_nonzero(delta)),
                'strict_reversals': int(((D * (D + e)) < 0).sum()),
                'tie_transitions': int(((delta != 0) & ((D == 0) | (D + e == 0))).sum())}

    plus, minus = movement(t * g), movement(-t * g)
    M = max(plus['A'], minus['A'])
    T = float(0.5 * ((D == 0) & (E != 0)).mean())
    assert abs(B - (plus['A'] + minus['A'] - T)) <= tol
    grid = []
    for index, c in enumerate(np.linspace(g.min(), g.max(), grid_points)):
        for sign in signs:
            grid.append({'c_grid_index': index, 'c': float(c), 'sign': sign,
                         **movement(sign * t * np.abs(g - c))})
    best_A = max(grid, key=lambda x: x['A'])
    best_Delta = max(grid, key=lambda x: abs(x['Delta']))
    assert best_A['A'] + tol >= M  # the two extremes include +/-tg up to a constant
    record = {'n_subjects': len(y), 'n_positive': len(pos), 'n_negative': len(neg),
              'pairs': len(D), 'retained_C': float(baseline.mean()), 't': t,
              'plus': plus, 'minus': minus, 'M': M, 'B': B, 'tie_correction': T,
              'F': best_A['A'], 'grid_max_A_witness': best_A,
              'grid_max_abs_Delta': abs(best_Delta['Delta']),
              'grid_max_abs_Delta_witness': best_Delta,
              'F_exceeds_M': bool(best_A['A'] > M + tol),
              'abs_Delta_exceeds_M': bool(abs(best_Delta['Delta']) > M + tol),
              'grid_evaluations': len(grid)}
    return record, grid, movement


def table_tex(summary):
    lines = [r'% Generated by b_robustness/run.py; do not edit numeric cells.',
             r'\ReserveTableSpace',
             r'\noindent\textbf{Table S8:} Bounded nonlinear component stress tests. Each row summarizes ten saved matched-centred Softplus fits with 60 training compounds. $M$ is the maximum movement over the entire scalar band $[-t,t]$, $F$ the largest movement on the folded-score grid, and $B$ the uniform magnitude-based bound. The final columns count draws with $F>M$ and with a grid value of $|\Delta|>M$, respectively.',
             r'\begin{small}', r'\setlength{\tabcolsep}{3pt}',
             r'\begin{longtable}{lrrrrrrr}', r'\toprule',
             r'Panel & $t$ & Pairs & Mean $M$ & Mean $F$ & Mean $B$ & $F>M$ & $|\Delta|>M$ \\',
             r'\midrule', r'\endfirsthead', r'\toprule',
             r'Panel & $t$ & Pairs & Mean $M$ & Mean $F$ & Mean $B$ & $F>M$ & $|\Delta|>M$ \\',
             r'\midrule', r'\endhead', r'\bottomrule', r'\endfoot']
    for r in summary:
        if r['panel'] == 'PHH' and r['t'] != 1:
            lines.append(r'\addlinespace')
        lines.append(f"{PANEL_NAMES[r['panel']]} & {r['t']} & {r['pairs']} & {r['mean_M']:.4f} & {r['mean_F']:.4f} & {r['mean_B']:.4f} & {r['F_exceeds_M']}/10 & {r['abs_Delta_exceeds_M']}/10 " + r'\\')
    lines += [r'\end{longtable}', r'\end{small}',
              r'\noindent\footnotesize The primary analysis uses $t=1$; $t=2,4,8$ are sensitivity analyses. Grid maxima need not attain the supremum over all admissible perturbations. The panels share fitted source draws and are not independent repetitions.\normalsize', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, default=HERE / 'results')
    ap.add_argument('--parameters', type=Path, default=HERE / 'parameters.json')
    args = ap.parse_args()
    cfg = json.loads(args.parameters.read_text(encoding='utf-8'))
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    exp = REPO / 'data/evidence/05_reconstruction/results/experiments'
    records, grid_rows, snapshots, provenance = [], [], [], []
    for panel in cfg['panels']:
        for seed in cfg['source_draw_seeds']:
            path = exp / f"n{cfg['training_compounds']}_seed{seed}_{panel}_scores.npz"
            ell, g, y, subjects = load_compounds(path, cfg['arm'])
            provenance.append({'path': path.relative_to(REPO).as_posix(), 'sha256': sha(path)})
            snapshots.append({'panel': panel, 'seed': seed, 'subjects': subjects})
            for t in cfg['multipliers']:
                r, grid, _ = evaluate(ell, g, y, t, cfg['fold_grid_points'],
                                      cfg['fold_signs'], cfg['validation_tolerance'])
                tag = {'panel': panel, 'seed': seed, 't': t}
                records.append({**tag, **r})
                grid_rows.extend({**tag, **row} for row in grid)
    summary = []
    for t in cfg['multipliers']:
        for panel in cfg['panels']:
            rs = [r for r in records if r['panel'] == panel and r['t'] == t]
            summary.append({'panel': panel, 't': t, 'draws': len(rs), 'pairs': rs[0]['pairs'],
                            'mean_M': float(np.mean([r['M'] for r in rs])),
                            'mean_F': float(np.mean([r['F'] for r in rs])),
                            'mean_B': float(np.mean([r['B'] for r in rs])),
                            'F_exceeds_M': sum(r['F_exceeds_M'] for r in rs),
                            'abs_Delta_exceeds_M': sum(r['abs_Delta_exceeds_M'] for r in rs)})
    toy = cfg['toy']
    ell = np.array(toy['positive_ell'] + toy['negative_ell'], dtype=float)
    g = np.array(toy['positive_g'] + toy['negative_g'], dtype=float)
    y = np.array([1]*len(toy['positive_ell']) + [0]*len(toy['negative_ell']))
    toy_result, _, calc = evaluate(ell, g, y, 1, cfg['fold_grid_points'],
                                   cfg['fold_signs'], cfg['validation_tolerance'])
    toy_result['explicit_fold'] = calc(toy['explicit_fold_sign'] * np.abs(g - toy['explicit_fold_c']))
    assert toy_result['plus']['A'] == .02 and toy_result['minus']['A'] == .02
    assert toy_result['explicit_fold']['A'] == toy_result['B'] == .04
    assert toy_result['explicit_fold']['Delta'] == -.04
    def save(name, obj):
        (out / name).write_text(json.dumps(obj, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    save('results.json', {'parameters_sha256': sha(args.parameters), 'provenance': provenance,
                          'toy': toy_result, 'summary': summary, 'records': records})
    save('compound_scores.json', snapshots)
    save('environment.json', {'python': sys.version, 'numpy': np.__version__, 'platform': platform.platform()})
    with (out / 'grid_results.csv').open('w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=list(grid_rows[0]))
        writer.writeheader()
        writer.writerows(grid_rows)
    (out / 'table_S8.tex').write_text(table_tex(summary), encoding='utf-8')
    print(f"Completed {len(records)} draw-panel-multiplier evaluations and {len(grid_rows)} folded perturbations.")
    print('No refitting; no sampling intervals; all tested perturbations obey their pairwise constraints and bounds.')
    for row in summary[:3]:
        print(f"t=1 {PANEL_NAMES[row['panel']]}: F>M in {row['F_exceeds_M']}/10; |Delta|>M in {row['abs_Delta_exceeds_M']}/10")
    print('Results:', out)


if __name__ == '__main__':
    main()
