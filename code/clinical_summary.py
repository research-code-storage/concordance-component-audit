"""Render both existing same-fit survival deletions; no model is fitted here."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]

def interval(o, closed_form=False):
    fmt = lambda x: ('$-$' if x < 0 else '') + f'{abs(x):.3f}'
    left, right = ('(', ')') if closed_form else ('[', ']')
    return r'{\footnotesize' + left + fmt(o['lower']) + ', ' + fmt(o['upper']) + right + '}'


def render(data, boot, ustat):
    lines = [r'% Generated by code/clinical_summary.py from the independently replayed survival scores;',
             r'% intervals from code/lung_bootstrap.py and code/lung_ustat.py.',
             r'\begin{table}[!htbp]', r'\small',
             r'\caption{Same-fit clinical component audit. Net concordance change ($\Delta$), observed pairwise movement ($A_\omega$) and the magnitude-based bound ($B_\omega$) describe complementary aspects of each deletion.}',
             r'\label{tab:clinical_audit}',
             r'\centering', r'\begin{tabular}{lrrrrr}', r'\toprule',
             r'Deleted component & $\Delta$ & $A_\omega$ & $B_\omega$ & Reversals & Ties \\',
             r'\midrule']
    for n_row, (key, label) in enumerate([('delete_age_sex', 'Age and sex'), ('delete_ecog', 'ECOG')]):
        r = data[key]
        b = boot[key]
        u = ustat[key]
        for q, k in [('Delta', 'net_change'), ('A', 'mean_absolute_pair_change'), ('B', 'tie_aware_bound')]:
            assert abs(b[q]['estimate'] - r[k]) < 1e-12, (key, q)
            assert abs(u[q]['estimate'] - r[k]) < 1e-12, (key, q)
        if n_row:
            lines.append(r'\addlinespace')
        assert r['changed_pairs'] == r['strict_reversals'] + r['tie_transitions']
        assert abs(r['net_change']) <= r['mean_absolute_pair_change'] + 1e-12
        assert r['mean_absolute_pair_change'] <= r['tie_aware_bound'] + 1e-12
        lines.append(label + ' & ' + ' & '.join(f'{r[k]:.4f}' for k in
                     ['net_change', 'mean_absolute_pair_change', 'tie_aware_bound']) +
                     f" & {r['strict_reversals']} & {r['tie_transitions']}" + r' \\')
        lines.append(' & ' + ' & '.join(interval(b[q]) for q in ('Delta', 'A', 'B')) + r' & & \\')
        lines.append(' & ' + ' & '.join(interval(u[q], True) for q in ('Delta', 'A', 'B')) + r' & & \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\par\smallskip\raggedright',
              f"Both deletions use the same fitted model and {data['n_comparable_pairs']} held-out comparable pairs. "
              r'$\Delta=C_\omega(f)-C_\omega(\ell)$. Reversals are strict sign changes; ',
              r'ties count transitions to or from a tie. The retained component is held fixed. '
              f"Brackets give 95\\% percentile intervals from {boot['replicates']} bootstrap resamples of the "
              f"{boot['n_patients']} held-out patients with the fitted coefficients fixed; parentheses give 95\\% normal "
              r'intervals with the closed-form variance of Proposition~\ref{prop:inference}.',
              r'\end{table}', '']
    return '\n'.join(lines)

def check():
    data = json.loads((ROOT / 'generated/survival_example.json').read_text())
    boot = json.loads((ROOT / 'generated/lung_bootstrap.json').read_text())
    ustat = json.loads((ROOT / 'generated/lung_ustat.json').read_text())
    result = render(data, boot, ustat)
    (ROOT / 'generated/clinical_summary.tex').write_text(result, encoding='utf-8')
    print('Both clinical deletions, all 10 displayed values, 6 bootstrap intervals, 6 closed-form intervals and pair definitions verified')

if __name__ == '__main__':
    check()
